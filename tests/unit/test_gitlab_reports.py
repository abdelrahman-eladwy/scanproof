"""GitLab Security Report adapters. Fixtures are REAL output of GitLab's analyzers
(security-products/semgrep:6, container-scanning:8) generated by scanproof-e2e fixtures;
the container scanning report is trimmed to 20 vulnerabilities."""

from __future__ import annotations

import json

import pytest

from scanproof.evidence.models import ScanType
from scanproof.models import InspectedJob, Job, JobStatus, Pipeline
from scanproof.policy.engine import Outcome, RequirementInput, evaluate_requirement
from scanproof.policy.models import Requirement
from scanproof.scanners.gitlab_report import GitLabContainerScanningAdapter, GitLabSastAdapter
from tests.conftest import FIXTURES

sast = GitLabSastAdapter()
cs = GitLabContainerScanningAdapter()
SAST_RAW = (FIXTURES / "gitlab-reports/gl-sast-report.json").read_bytes()
CS_RAW = (FIXTURES / "gitlab-reports/gl-container-scanning-report.json").read_bytes()
DIGEST = "sha256:" + "c" * 64


def modified(raw: bytes, fn) -> bytes:
    data = json.loads(raw)
    fn(data)
    return json.dumps(data).encode()


def test_real_sast_report() -> None:
    ev = sast.parse(SAST_RAW)
    assert ev.parseable and ev.scan_type is ScanType.SAST
    assert ev.tool_version == "semgrep 1.181.0 (GitLab analyzer semgrep 6.30.0)"
    assert ev.scanner_errors == []
    assert ev.findings.total == 2 and ev.findings.by_severity == {"HIGH": 2}
    assert ev.scope is None  # the format does not list scanned files


def test_real_container_report_has_image_but_no_digest() -> None:
    ev = cs.parse(CS_RAW)
    assert ev.parseable and ev.scan_type is ScanType.CONTAINER
    assert ev.tool_version.startswith("trivy 0.72.0")
    assert ev.findings.total == 20
    assert ev.target.artifact_name == "python:3.12-slim"
    assert ev.target.digests() == set()


def test_container_report_scanned_by_digest() -> None:
    image = f"registry.example.com/app@{DIGEST}"

    def by_digest(d):
        for v in d["vulnerabilities"]:
            v["location"]["image"] = image

    ev = cs.parse(modified(CS_RAW, by_digest))
    assert ev.target.digests() == {DIGEST}


def test_container_report_without_findings_has_unknown_target() -> None:
    ev = cs.parse(modified(CS_RAW, lambda d: d.update(vulnerabilities=[])))
    assert ev.parseable and ev.findings.total == 0
    assert ev.target is None


def test_container_report_with_several_images_is_not_bound() -> None:
    def two_images(d):
        d["vulnerabilities"][0]["location"]["image"] = "other:1"

    ev = cs.parse(modified(CS_RAW, two_images))
    assert ev.target.repo_digests is None


def test_failed_scan_status_is_a_scanner_error() -> None:
    def failed(d):
        d["scan"]["status"] = "failure"
        d["scan"]["messages"] = [
            {"level": "fatal", "value": "analyzer crashed"},
            {"level": "info", "value": "just info"},
        ]

    ev = sast.parse(modified(SAST_RAW, failed))
    assert [e.type for e in ev.scanner_errors] == ["scan.status", "scan.message"]
    assert ev.scanner_errors[1].message == "analyzer crashed"


def test_missing_status_means_errors_unknown() -> None:
    ev = sast.parse(modified(SAST_RAW, lambda d: d["scan"].pop("status")))
    assert ev.parseable and ev.scanner_errors is None


@pytest.mark.parametrize(
    ("adapter", "raw", "reason"),
    [
        (sast, CS_RAW, "requirement expects 'sast'"),
        (cs, SAST_RAW, "requirement expects 'container_scanning'"),
        (
            sast,
            (FIXTURES / "semgrep/semgrep-clean.json").read_bytes(),
            "Not a GitLab security report",
        ),
        (sast, b"[]", "must be a JSON object"),
        (
            sast,
            b'{"version": "15", "scan": {"type": "sast"}, "vulnerabilities": {}}',
            "must be a list",
        ),
    ],
)
def test_wrong_reports_rejected(adapter, raw, reason) -> None:
    ev = adapter.parse(raw)
    assert not ev.parseable
    assert reason in ev.parse_error


def test_policy_scope_checks_are_unknown_for_gitlab_sast() -> None:
    """Scope checks can't be satisfied by this format; they must not silently pass."""
    sha = "a" * 40
    job = Job(id=1, name="semgrep-sast", status=JobStatus.SUCCESS, commit_sha=sha)
    inspected = InspectedJob(
        name=job.name, stage="test", latest=job, attempt_ids=[1], commit_matches_pipeline=True
    )
    req = Requirement.model_validate(
        {
            "id": "S",
            "tool": "gitlab-sast",
            "job_name": "semgrep-sast",
            "report_path": "gl-sast-report.json",
            "checks": {"scanner_errors_allowed": 0, "minimum_scanned_files": 1},
        }
    )
    res = evaluate_requirement(
        req,
        Pipeline(id=1, sha=sha, status="success"),
        RequirementInput(job=inspected, evidence=sast.parse(SAST_RAW)),
    )
    by_check = {c.check: c.outcome for c in res.checks}
    assert by_check["scanner_errors"] is Outcome.PASS
    assert by_check["minimum_scanned_files"] is Outcome.UNKNOWN
